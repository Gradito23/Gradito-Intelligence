export async function getPvConfig(adminClient) {
  const row = await loadConnection(adminClient);
  const redirectUri = Deno.env.get('PERFECT_VENUE_REDIRECT_URI')?.trim() || 'https://ai.gradito.com/oauth/perfect-venue/callback';
  let clientId = row?.client_id?.trim() || '';
  let clientSecret = '';
  if (row?.encrypted_client_secret && row.client_secret_iv) {
    clientSecret = await resolveSecret(adminClient, {
      encrypted: row.encrypted_client_secret,
      iv: row.client_secret_iv
    });
  }
  if (!clientId) {
    clientId = Deno.env.get('PERFECT_VENUE_CLIENT_ID')?.trim() || '';
  }
  if (!clientSecret) {
    clientSecret = Deno.env.get('PERFECT_VENUE_CLIENT_SECRET')?.trim() || '';
  }
  if (!clientId || !clientSecret) {
    throw new Error('Configure Perfect Venue client ID and secret under Admin → Integrations → Perfect Venue');
  }
  return {
    clientId,
    clientSecret,
    redirectUri
  };
}
function basicAuthHeader(clientId, clientSecret) {
  const encoded = btoa(`${clientId}:${clientSecret}`);
  return `Basic ${encoded}`;
}
function unwrapData(payload) {
  if (!payload || typeof payload !== 'object') return payload;
  const obj = payload;
  if (obj.data !== undefined) return obj.data;
  return payload;
}
export async function pvApiGet(accessToken, path, query) {
  const url = new URL(`${PV_API_BASE}${path}`);
  if (query) {
    Object.entries(query).forEach(([k, v]) => {
      if (v !== undefined && v !== '') url.searchParams.set(k, v);
    });
  }
  let lastError: Error | null = null;
  for (let attempt = 0; attempt < PV_API_429_MAX_ATTEMPTS; attempt++) {
    const response = await fetch(url.toString(), {
      headers: {
        Authorization: `Bearer ${accessToken}`,
        Accept: 'application/json',
        'PV-Version': PV_API_VERSION,
      },
    });
    if (response.status === 429) {
      const text = await response.text().catch(() => '');
      lastError = new Error(`Perfect Venue API ${path} failed (429): ${text.slice(0, 200)}`);
      if (attempt < PV_API_429_MAX_ATTEMPTS - 1) {
        await sleep(pvApi429DelayMs(attempt, response.headers.get('Retry-After')));
        continue;
      }
      throw lastError;
    }
    if (!response.ok) {
      const text = await response.text().catch(() => '');
      throw new Error(`Perfect Venue API ${path} failed (${response.status}): ${text.slice(0, 200)}`);
    }
    const payload = await response.json();
    return unwrapData(payload);
  }
  throw lastError ?? new Error(`Perfect Venue API ${path} failed (429)`);
}

/** GET with proactive token resolution and one 401 → refresh → retry. */
export async function pvApiGetWithAuth(
  adminClient,
  row: Awaited<ReturnType<typeof loadConnection>>,
  path: string,
  query?: Record<string, string>,
) {
  if (!row) throw new Error('Perfect Venue is not connected');
  let token = await resolveAccessToken(adminClient, row);
  try {
    return await pvApiGet(token, path, query);
  } catch (err) {
    if (!isPvApiUnauthorized(err)) throw err;
    token = await refreshAndStoreTokens(adminClient, row);
    return await pvApiGet(token, path, query);
  }
}

