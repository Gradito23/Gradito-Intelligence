function applyPvFieldLocks(
  patch: Record<string, unknown>,
  locks: Record<string, unknown> | null | undefined,
): Record<string, unknown> {
  if (!locks || typeof locks !== 'object') return patch;
  const next = { ...patch };
  for (const [key, locked] of Object.entries(locks)) {
    if (locked && PV_LOCKABLE_CRM_FIELDS.has(key)) delete next[key];
  }
  return next;
}

function pruneEmptyPvCrmFields(patch: Record<string, unknown>): Record<string, unknown> {
  const next = { ...patch };
  if (!next.service_area) delete next.service_area;
  if (!next.client_name) delete next.client_name;
  if (!next.date) delete next.date;
  if (!next.event_type) delete next.event_type;
  if (next.guest_count == null) delete next.guest_count;
  if (!next.status) delete next.status;
  if (!next.experience_type) delete next.experience_type;
  if (!next.closer_id) delete next.closer_id;
  if (!next.client_id) delete next.client_id;
  if (next.client_revenue == null) delete next.client_revenue;
  return next;
}

/** Fetch full event records when list payload omits custom fields (capped per chunk). */
export async function enrichEventsWithPvDetails(
  adminClient,
  row: NonNullable<Awaited<ReturnType<typeof loadConnection>>>,
  events: Record<string, unknown>[],
) {
  if (!events?.length) return;
  const sample = events[0];
  if (sample?.id) {
    console.info('pv-sync events page sample', {
      id: sample.id,
      custom_field_count: buildCustomFieldsArray(sample).length,
    });
  }
  let fetches = 0;
  for (let i = 0; i < events.length && fetches < MAX_EVENT_DETAIL_FETCHES_PER_CHUNK; i++) {
    const ev = events[i];
    if (!ev?.id || !pvEventNeedsDetailFetch(ev)) continue;
    try {
      const data = await pvApiGetWithAuth(adminClient, row, `/events/${ev.id}`);
      const full = (data && typeof data === 'object' && 'event' in data)
        ? (data as { event: Record<string, unknown> }).event
        : data;
      if (full && typeof full === 'object') {
        events[i] = { ...ev, ...full };
      }
      fetches += 1;
    } catch (err) {
      if (isPvApiRateLimited(err)) throw err;
      console.warn(`enrichEventsWithPvDetails ${ev.id}:`, err instanceof Error ? err.message : err);
    }
  }
}

/** Fetch contacts referenced on this events page into the per-chunk cache (capped). */
export async function hydrateContactsForEvents(
  adminClient,
  row: NonNullable<Awaited<ReturnType<typeof loadConnection>>>,
  events: { contact_id?: string }[],
  cache: Map<string, unknown>,
) {
  const missing = [...new Set(
    (events ?? [])
      .map((e) => e.contact_id)
      .filter((id): id is string => Boolean(id) && !cache.has(id)),
  )].slice(0, MAX_CONTACT_FETCHES_PER_BATCH);

  for (const contactId of missing) {
    try {
      if (PV_CONTACT_FETCH_DELAY_MS > 0) await sleep(PV_CONTACT_FETCH_DELAY_MS);
      const data = await pvApiGetWithAuth(adminClient, row, `/contacts/${contactId}`);
      const contact = (data && typeof data === 'object' && 'contact' in data)
        ? (data as { contact: unknown }).contact
        : data;
      if (contact && typeof contact === 'object') cache.set(contactId, contact);
    } catch (err) {
      if (isPvApiRateLimited(err)) throw err;
      console.warn(`hydrateContactsForEvents ${contactId}:`, err instanceof Error ? err.message : err);
    }
  }
}

